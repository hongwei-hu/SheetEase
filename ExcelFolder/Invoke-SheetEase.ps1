[CmdletBinding()]
param(
    [ValidateSet('Check', 'Export')]
    [string]$Mode = 'Check',
    [string]$ConfigPath,
    [string]$ReportPath,
    [string]$ToolRoot,
    [switch]$UseExecutable,
    [switch]$AllowCleanup,
    [switch]$NoDiff
)

$ErrorActionPreference = 'Stop'
if ([string]::IsNullOrWhiteSpace($ConfigPath)) {
    $ConfigPath = Join-Path $PSScriptRoot 'sheet_config.json'
}
if ([string]::IsNullOrWhiteSpace($ReportPath)) {
    $ReportPath = Join-Path $PSScriptRoot '.sheetease\agent-export-report.json'
}
if ([string]::IsNullOrWhiteSpace($ToolRoot)) {
    $ToolRoot = Split-Path $PSScriptRoot -Parent
}
$ConfigPath = [System.IO.Path]::GetFullPath($ConfigPath)
$ReportPath = [System.IO.Path]::GetFullPath($ReportPath)
$ToolRoot = [System.IO.Path]::GetFullPath($ToolRoot)
$runStartedAt = [System.DateTimeOffset]::UtcNow

$exportArguments = @(
    '--headless'
    '--config', $ConfigPath
    '--report', $ReportPath
)
if ($Mode -eq 'Check') {
    $exportArguments += '--dry-run'
}
if (-not $AllowCleanup) {
    $exportArguments += '--no-cleanup'
}
if ($NoDiff) {
    $exportArguments += '--no-diff'
}

if ($UseExecutable) {
    $executable = Join-Path $PSScriptRoot 'SheetEase.exe'
    if (-not (Test-Path -LiteralPath $executable -PathType Leaf)) {
        throw "SheetEase.exe was not found: $executable"
    }
    $argumentText = ($exportArguments | ForEach-Object {
        '"' + ($_ -replace '"', '\"') + '"'
    }) -join ' '
    $process = Start-Process -FilePath $executable -ArgumentList $argumentText -Wait -PassThru
    $exitCode = $process.ExitCode
}
else {
    if (-not (Test-Path -LiteralPath (Join-Path $ToolRoot 'ExcelExportTool') -PathType Container)) {
        throw "Excel2JsonTool source directory was not found: $ToolRoot"
    }

    $pyLauncher = Get-Command py -ErrorAction SilentlyContinue
    $python = Get-Command python -ErrorAction SilentlyContinue
    Push-Location $ToolRoot
    try {
        if ($pyLauncher) {
            & $pyLauncher.Source -3 -m ExcelExportTool.export_all @exportArguments
        }
        elseif ($python) {
            & $python.Source -m ExcelExportTool.export_all @exportArguments
        }
        else {
            throw 'Neither py nor python was found.'
        }
        $exitCode = $LASTEXITCODE
    }
    finally {
        Pop-Location
    }
}

if (-not (Test-Path -LiteralPath $ReportPath -PathType Leaf)) {
    throw "The export process did not create a report: $ReportPath"
}

$report = Get-Content -LiteralPath $ReportPath -Raw -Encoding UTF8 | ConvertFrom-Json
$reportedFinishedAt = [System.DateTimeOffset]::Parse($report.finished_at)
if ($reportedFinishedAt -lt $runStartedAt.AddSeconds(-1)) {
    throw "The report is stale and was not generated by this run: $ReportPath"
}
if ([int]$report.exit_code -ne [int]$exitCode) {
    throw "Process/report exit codes differ: process=$exitCode, report=$($report.exit_code)"
}
Write-Output "SHEETEASE_STATUS=$($report.status)"
Write-Output "SHEETEASE_EXIT_CODE=$exitCode"
Write-Output "SHEETEASE_REPORT=$ReportPath"
exit $exitCode
